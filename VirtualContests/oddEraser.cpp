int gcd(int a, int b) {
    if (b == 0)
        return a;
    return gcd(b, a%b);
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(0);

    int t; cin >> t;

    while (t--) {
        int n; cin >> n;

        vector<int> nums(n); for (auto &i : nums) cin >> i;

        // basically are able to remove the middle element if we pick some amount of indices such that there are
        // exactly some on the left and stuff but the trick is that everything will be bounded by the first and last
        // element because those its not possible for those to be the middle element
        // gcd is bounded by the first and last element because we are able to delete all in the middle and end
        cout << gcd(nums[0], nums[n - 1]) << endl;
    }
}
