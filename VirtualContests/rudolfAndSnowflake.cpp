// just precompute

unordered_set<int> dp;

void solve() {
    int n; cin >> n;

    // looking for any k that just works
    if (dp.count(n)) {
        cout << "YES\n";
    } else {
        cout << "NO\n";
    }
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(0);
    int t = 1;
    cin >> t;

    for (int k = 2; k <= 1000; k++) {
        int currentSum = 1 + k;
        int currentPower = k;

        while (currentSum < 1e6) {
            currentPower *= k;
            currentSum += currentPower;

            if (currentSum < 1e6) {
                dp.insert(currentSum);
            }
        }
    }

    while (t--) {
        solve();
    }
}
